"""Bake the interface's material swatches from BUSHED's photo-derived pixel textures.

BUSHED (the owner's lumberjack game) ships seamless, palette-quantised pixel-art textures made from CC0
Poly Haven scans. The interface borrows a few of them as small tiles (worn table boards, duck canvas,
brown leather, herringbone wool), palette-quantised again to <= 40 colours and written as a JS module
(src/ui/px/textiles.js) so frames can be painted synchronously. Colours are graded into the calm palette
at runtime (calm.js). Credits: docs/credits/ui3.md.

    python3 art/ui/make_textiles.py <bushed>/public/assets/textures src/ui/px/textiles.js
"""
import base64
import sys

from PIL import Image

SRC, OUT = sys.argv[1], sys.argv[2]
# name: (file, downscale factor, crop box after downscale or None, colours)
TILES = {
    'boards': ('building/floor_boards_albedo.png', 2, (0, 0, 256, 128), 40),
    'canvas': ('places/canvas.png', 2, None, 24),
    'leather': ('places/leather.png', 2, None, 32),
    'wool': ('places/wool_grey.png', 2, None, 24),
}

lines = [
    '// GENERATED by art/ui/make_textiles.py from BUSHED\'s photo-derived pixel textures (CC0 Poly Haven scans:',
    '// wood_floor_worn, brown_leather, poly_wool_herringbone; BUSHED\'s procedural duck canvas).',
    '// Each tile: { w, h, pal: [\'#rrggbb\'...], idx: base64 bytes (palette index per texel, row-major) }. Seamless.',
    '// Decode with tile(name) in materials.ts. Credits: docs/credits/ui3.md. Do not edit by hand.',
    'export const TEXTILES = {',
]
for name, (f, k, crop, ncol) in TILES.items():
    im = Image.open(f'{SRC}/{f}').convert('RGB')
    w, h = im.size
    im = im.resize((w // k, h // k), Image.BOX)  # integer box filter keeps the tile seamless
    if crop:
        im = im.crop(crop)
    q = im.quantize(colors=ncol, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[: ncol * 3]
    idx = bytes(q.get_flattened_data()) if hasattr(q, 'get_flattened_data') else bytes(q.getdata())
    hexes = ["'#%02x%02x%02x'" % tuple(pal[i * 3: i * 3 + 3]) for i in range(ncol)]
    lines.append(f"  {name}: {{ w: {q.size[0]}, h: {q.size[1]}, pal: [{', '.join(hexes)}], idx: '{base64.b64encode(idx).decode()}' }},")
    print(name, q.size, len(idx))
lines.append('};')
open(OUT, 'w').write('\n'.join(lines) + '\n')
