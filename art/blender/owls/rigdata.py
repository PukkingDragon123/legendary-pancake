"""Write src/owl/rig.gen.ts from the owl builds' rig sheets (art/blender/_build/owls/<id>.rig.json): every model's
joint pivots, anchors, eye decals and size, so the game knows an owl's frame before its GLB has loaded.

    python3 -I art/blender/owls/rigdata.py
"""
import glob
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
BUILD = os.path.join(ROOT, 'art', 'blender', '_build', 'owls')
OUT = os.path.join(ROOT, 'src', 'owl', 'rig.gen.ts')
KEEP = ('pivots', 'parents', 'anchors', 'eyes', 'min', 'max', 'height', 'dims', 'tris')

rigs = {}
old = {}
if os.path.exists(OUT):  # (keep the models that were not rebuilt in this checkout)
    src = open(OUT).read()
    a = src.index('= ') + 2
    b = src.rindex(';')
    old = json.loads(src[a:b])
for path in sorted(glob.glob(os.path.join(BUILD, '*.rig.json'))):
    m = json.load(open(path))
    rigs[m['id']] = {k: m[k] for k in KEEP if k in m}
merged = dict(old)
merged.update(rigs)
for mid, m in merged.items():  # the still portraits made by art/blender/owls/stills.cjs (shown while a model loads)
    shots = [p for p in ('face', 'full') if os.path.exists(os.path.join(ROOT, 'public', 'models', 'owls', f'{mid}.{p}.webp'))]
    if shots:
        m['shots'] = shots
    else:
        m.pop('shots', None)
merged = dict(sorted(merged.items()))
with open(OUT, 'w') as f:
    f.write('// Generated by art/blender/owls/rigdata.py from the Blender owl builds: do not edit by hand.\n')
    f.write('// Units: toy millimetres in the game frame (x, y up, z toward the viewer).\n')
    f.write("import type { OwlRigData } from './rigtypes.ts';\n\n")
    f.write('export const OWL_RIGS: Record<string, OwlRigData> = ' + json.dumps(merged, separators=(',', ':')) + ';\n')
print('wrote', OUT, ', '.join(merged))

# ---- the outfit pieces that exist as toy GLBs (art/blender/owls/outfits.py): src/owl/outfits.gen.ts
PB = os.path.join(ROOT, 'art', 'blender', '_build', 'outfits')
POUT = os.path.join(ROOT, 'src', 'owl', 'outfits.gen.ts')
pieces = {}
if os.path.exists(POUT):
    src = open(POUT).read()
    pieces = json.loads(src[src.index('= ') + 2:src.rindex(';')])
for path in sorted(glob.glob(os.path.join(PB, '*.piece.json'))):
    m = json.load(open(path))
    if os.path.exists(os.path.join(ROOT, 'public', 'models', 'outfits', m['id'] + '.glb')):
        pieces[m['id']] = {'anchor': m['anchor'], 'hidesTufts': bool(m.get('hides'))}
pieces = {k: v for k, v in pieces.items() if os.path.exists(os.path.join(ROOT, 'public', 'models', 'outfits', k + '.glb'))}
with open(POUT, 'w') as f:
    f.write('// Generated by art/blender/owls/rigdata.py from the outfit builds: do not edit by hand.\n')
    f.write("import type { PieceModel } from './outfits.ts';\n\n")
    f.write('export const PIECE_MODEL_LIST: Record<string, PieceModel> = ' + json.dumps(dict(sorted(pieces.items())), separators=(',', ':')) + ';\n')
print('wrote', POUT, ', '.join(sorted(pieces)))
