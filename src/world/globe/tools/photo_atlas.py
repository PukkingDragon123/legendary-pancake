"""Turn the place photographs into one small pixel-art atlas for the globe's postcards and passport.

    ~/.cache/lowpix-venv/bin/python src/world/globe/tools/photo_atlas.py <photos dir from fetch_photos.py>

Each photo is cropped to 5:3, shrunk to 180 x 108, graded to the calm Hoot Hollow mood (a little faded, warm lamp
highlights, slate shadows, no pure black), then posterised with an ordered (Bayer) dither onto a small palette of
its own, so it reads as crisp hand-placed pixel art. Writes public/img/places/places.webp (a 4 x 5 grid) and
src/ui/globe/photos.ts (atlas layout and each photo's credit).
"""
import json
import os
import sys

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
ORDER = ["highlands", "kyoto", "paris", "venice", "santorini", "sahara", "grandcanyon", "cappadocia", "tajmahal", "amazon",
         "iceland", "machupicchu", "serengeti", "banff", "petra", "angkor", "reef", "rio", "milford", "antarctica"]
TW, TH, COLS = 180, 108, 4
# where to centre the 5:3 crop (fractions of the photo), when the subject is off-centre
FOCUS = {"paris": (0.5, 0.45), "petra": (0.5, 0.55)}
BAYER = (np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]) + 0.5) / 16 - 0.5


def treat(im, focus=(0.5, 0.5)):
    w, h = im.size
    if w / h > TW / TH:
        cw, ch = int(h * TW / TH), h
    else:
        cw, ch = w, int(w * TH / TW)
    x0 = int(max(0, min(w - cw, focus[0] * w - cw / 2)))
    y0 = int(max(0, min(h - ch, focus[1] * h - ch / 2)))
    im = im.crop((x0, y0, x0 + cw, y0 + ch)).resize((TW, TH), Image.LANCZOS)
    a = np.asarray(im.convert("RGB"), np.float64) / 255
    l = a @ np.array([0.2126, 0.7152, 0.0722])
    a = l[..., None] + (a - l[..., None]) * 0.82                                   # a little faded
    a += np.array([0.05, 0.025, -0.03]) * np.clip((l[..., None] - 0.4) / 0.5, 0, 1)    # lamp-warm highlights
    a += np.array([-0.015, 0.005, 0.03]) * np.clip(1 - l[..., None] / 0.35, 0, 1)     # slate shadows
    a = 0.045 + a * 0.93                                                              # never pure black or white
    a = np.clip(a, 0, 1)
    # posterise: an ordered dither onto the photo's own 40-colour palette
    by = BAYER[np.arange(TH)[:, None] % 4, np.arange(TW)[None, :] % 4]
    pal_img = Image.fromarray((a * 255).astype(np.uint8)).quantize(colors=40, method=Image.Quantize.MEDIANCUT)
    pal = np.array(pal_img.getpalette()[:40 * 3], np.float64).reshape(-1, 3) / 255
    d = a + by[..., None] * 0.09
    idx = np.argmin(((d[:, :, None, :] - pal[None, None]) ** 2).sum(-1), axis=2)
    return (pal[idx] * 255).astype(np.uint8)


def main():
    src = sys.argv[1]
    credits = json.load(open(os.path.join(src, "credits.json")))
    rows = (len(ORDER) + COLS - 1) // COLS
    atlas = np.zeros((rows * TH, COLS * TW, 3), np.uint8)
    for i, p in enumerate(ORDER):
        f = os.path.join(src, f"{p}.jpg")
        if not os.path.exists(f):
            print("missing", p)
            continue
        t = treat(Image.open(f), FOCUS.get(p, (0.5, 0.5)))
        r, c = divmod(i, COLS)
        atlas[r * TH:(r + 1) * TH, c * TW:(c + 1) * TW] = t
    out = os.path.join(ROOT, "public", "img", "places")
    os.makedirs(out, exist_ok=True)
    Image.fromarray(atlas).save(os.path.join(out, "places.webp"), lossless=True, method=6)
    print("atlas", os.path.getsize(os.path.join(out, "places.webp")) // 1024, "KB")
    ts = ["// Generated by src/world/globe/tools/photo_atlas.py: the place photographs (Wikimedia Commons, free licences),",
          "// pixel-art treated and packed into public/img/places/places.webp. [globe] OWNED BY THE GLOBE BUILDER.",
          "export interface PhotoCredit { title: string; author: string; licence: string; url: string }",
          f"export const PHOTO_ATLAS = {{ src: 'img/places/places.webp', w: {COLS * TW}, h: {rows * TH}, tw: {TW}, th: {TH}, cols: {COLS} }};",
          f"export const PHOTO_ORDER: string[] = {json.dumps(ORDER)};",
          "export const PHOTO_CREDIT: Record<string, PhotoCredit> = {"]
    for p in ORDER:
        c = credits.get(p)
        if c:
            ts.append(f"  {p}: {json.dumps({'title': c['title'][5:].rsplit('.', 1)[0], 'author': c['author'], 'licence': c['licence'], 'url': c['url']}, ensure_ascii=False)},")
    ts.append("};")
    open(os.path.join(ROOT, "src", "ui", "globe", "photos.ts"), "w").write("\n".join(ts) + "\n")


if __name__ == "__main__":
    main()
